const special = (
  id: number,
  name: string,
  kind: SquareKind,
  tax = 0,
): Square => ({
  id,
  name,
  kind,
  price: 0,
  mortgage: 0,
  rents: [],
  buildCost: 0,
  tax,
});
const country = (
  id: number,
  name: string,
  group: string,
  color: string,
  price: number,
  rents: number[],
  buildCost: number,
): Square => ({
  id,
  name,
  kind: "country",
  group,
  color,
  price,
  mortgage: price / 2,
  rents,
  buildCost,
});
